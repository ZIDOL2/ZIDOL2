// 원시타입과 객체타입
/*
    1. 원시타입
    Number, String, Boolean, undefined, null, Symbol, BigInt 등
    값 자체로써 변수에 저장되고 복사 된다.
    불변값이다(메모리의 값을 수정하지 않는다.)
*/

/*
    2. 객체타입
    Object, Array, Function 등
    참조값을 통해 변수에 저장되고 복사된다.
    가변값이다.(메모리의 값을 수정할 수 있다.)

    2-1. 객체타입 주의사항
      1) 의도치 않게 값이 수정될 수 있다.
      2) 객체간의 비교는 기본적으로 참조값을 기준으로 이루어진다.
      3) 배열과 함수도 사실 객체이다.
*/
